# =============================================================================
#  ac6_setup.ps1  -  make this Keil project build with ARM Compiler 6 (armclang)
#
#  What it does (idempotent, safe to run any time):
#    1. finds startup_*.s that the project uses and converts it from armasm
#       syntax to armclang (GNU) syntax -> <name>_ac6.s (master copy) and
#       writes it back as the file the project builds
#    2. forces ARM Compiler 6 and "Assembler = armclang (GNU syntax)"
#    3. adds options that silence the two harmless AC6.22 diagnostics
#    4. keeps a backup of the original project file and original startup
#
#  Run after every CubeMX "GENERATE CODE", or whenever the chip is changed.
#  Stack size can be changed with:  ac6_setup.bat 0x2000
# =============================================================================
param([string]$StackSize = '0x1000')

$ErrorActionPreference = 'Stop'
$dir = Split-Path -Parent $MyInvocation.MyCommand.Path

$projFile = Get-ChildItem $dir -Filter '*.uvprojx' | Select-Object -First 1
if (-not $projFile) { throw 'No .uvprojx found. Put this script next to the project file.' }
$uvproj = $projFile.FullName

if (Get-Process -Name UV4 -ErrorAction SilentlyContinue) {
    Write-Host '[INFO] Keil uVision is running: close the project and reopen it after this script.' -ForegroundColor Yellow
}

$enc = New-Object System.Text.UTF8Encoding($false)
$t = [System.IO.File]::ReadAllText($uvproj)

# ---------------------------------------------------------------- 1. startup
$m = [regex]::Match($t, '<FilePath>([^<]*startup_[^<]*\.s)</FilePath>')
if (-not $m.Success) { throw 'No startup_*.s entry found in the project file.' }
$rel = $m.Groups[1].Value
$startPath = Join-Path $dir $rel
$baseName = [System.IO.Path]::GetFileNameWithoutExtension($startPath)
$masterPath = Join-Path (Split-Path $startPath) ($baseName + '_ac6.s')

function ConvertFrom-Armasm([string]$text, [string]$stackSize) {
    $lines = $text -split "`r?`n"

    # constants defined with EQU (e.g. BootRAM EQU 0xF108F85F)
    $equs = @{}
    foreach ($l in $lines) {
        if ($l -match '^\s*([A-Za-z_]\w*)\s+EQU\s+(0x[0-9A-Fa-f]+|\d+)') { $equs[$Matches[1]] = $Matches[2] }
    }

    # vector table entries (DCD ...)
    $vec = New-Object System.Collections.Generic.List[string]
    $inVec = $false
    foreach ($l in $lines) {
        if (-not $inVec -and $l -match '^\s*__Vectors\s+DCD\s+(\S+)') { $inVec = $true; $vec.Add($Matches[1]); continue }
        if ($inVec) {
            if ($l -match '^\s*__Vectors_End') { break }
            if ($l -match '^\s*DCD\s+(\S+)') { $vec.Add($Matches[1]) }
        }
    }
    if ($vec.Count -lt 8) { throw 'Cannot parse the vector table of the startup file.' }

    # weak handlers exported in Default_Handler
    $handlers = New-Object System.Collections.Generic.List[string]
    foreach ($l in $lines) {
        if ($l -match '^\s*EXPORT\s+([A-Za-z_]\w*)\s+\[WEAK\]') {
            $n = $Matches[1]
            if ($n -ne 'Reset_Handler' -and $n -ne 'Default_Handler' -and $n -ne '__Vectors') { $handlers.Add($n) }
        }
    }

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('/*==============================================================================')
    [void]$sb.AppendLine('  ' + $baseName + '.s  -  generated by ac6_setup.ps1, do not edit by hand.')
    [void]$sb.AppendLine('  Vector table + reset handler for ARM Compiler 6 (armclang, GNU syntax).')
    [void]$sb.AppendLine('  Stack size is set by ac6_setup.bat <size>  (default 0x1000 = 4 KB)')
    [void]$sb.AppendLine('==============================================================================*/')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('  .syntax unified')
    [void]$sb.AppendLine('  .thumb')
    [void]$sb.AppendLine('  .eabi_attribute 24, 1')
    [void]$sb.AppendLine('')
    if ($equs.Count -gt 0) {
        foreach ($k in $equs.Keys) {
            if ($k -eq 'Stack_Size' -or $k -eq 'Heap_Size') { continue }
            [void]$sb.AppendLine('  .equ ' + $k + ', ' + $equs[$k])
        }
        [void]$sb.AppendLine('')
    }
    [void]$sb.AppendLine('/* ---------------- stack ---------------- */')
    [void]$sb.AppendLine('  .equ  Stack_Size, ' + $stackSize)
    [void]$sb.AppendLine('  .section .stack, "aw", %nobits')
    [void]$sb.AppendLine('  .align 3')
    [void]$sb.AppendLine('Stack_Mem:')
    [void]$sb.AppendLine('  .space Stack_Size')
    [void]$sb.AppendLine('__initial_sp:')
    [void]$sb.AppendLine('  .global __initial_sp')
    [void]$sb.AppendLine('  .global Stack_Mem')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('/* ---------------- reset handler ---------------- */')
    [void]$sb.AppendLine('  .section .text.Reset_Handler,"ax",%progbits')
    [void]$sb.AppendLine('  .global Reset_Handler')
    [void]$sb.AppendLine('  .type Reset_Handler, %function')
    [void]$sb.AppendLine('Reset_Handler:')
    [void]$sb.AppendLine('  ldr r0, =SystemInit')
    [void]$sb.AppendLine('  blx r0')
    [void]$sb.AppendLine('  ldr r0, =__main')
    [void]$sb.AppendLine('  bx  r0')
    [void]$sb.AppendLine('  .size Reset_Handler, .-Reset_Handler')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('/* ---------------- default handler ---------------- */')
    [void]$sb.AppendLine('  .section .text.Default_Handler,"ax",%progbits')
    [void]$sb.AppendLine('  .global Default_Handler')
    [void]$sb.AppendLine('  .type Default_Handler, %function')
    [void]$sb.AppendLine('Default_Handler:')
    [void]$sb.AppendLine('Infinite_Loop:')
    [void]$sb.AppendLine('  b Infinite_Loop')
    [void]$sb.AppendLine('  .size Default_Handler, .-Default_Handler')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('/* ---------------- vector table ---------------- */')
    [void]$sb.AppendLine('  .section RESET,"a",%progbits')
    [void]$sb.AppendLine('  .global __Vectors')
    [void]$sb.AppendLine('  .global __Vectors_End')
    [void]$sb.AppendLine('  .global __Vectors_Size')
    [void]$sb.AppendLine('  .align 2')
    [void]$sb.AppendLine('__Vectors:')
    foreach ($v in $vec) {
        if ($v -match '^[0-9]') { [void]$sb.AppendLine('  .word ' + $v) }
        elseif ($equs.ContainsKey($v)) { [void]$sb.AppendLine('  .word ' + $v) }
        else { [void]$sb.AppendLine('  .word ' + $v) }
    }
    [void]$sb.AppendLine('__Vectors_End:')
    [void]$sb.AppendLine('  .equ __Vectors_Size, __Vectors_End - __Vectors')
    [void]$sb.AppendLine('')
    foreach ($h in $handlers) {
        [void]$sb.AppendLine('  .weak ' + $h)
        [void]$sb.AppendLine('  .thumb_set ' + $h + ',Default_Handler')
    }
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('  .end')
    return $sb.ToString()
}

$curText = if (Test-Path $startPath) { [System.IO.File]::ReadAllText($startPath) } else { '' }
$isGnu = $curText -match '\.syntax\s+unified'

if ($isGnu) {
    # already armclang syntax: only refresh stack size if asked
    if (Test-Path $masterPath) {
        Copy-Item $masterPath $startPath -Force
    } else {
        Copy-Item $startPath $masterPath -Force
    }
} else {
    if (-not (Test-Path $startPath)) { throw ('startup file not found: ' + $startPath) }
    # keep the original armasm file once
    $origBak = Join-Path (Split-Path $startPath) ($baseName + '_armasm.s.bak')
    if (-not (Test-Path $origBak)) { Copy-Item $startPath $origBak -Force }
    $gnu = ConvertFrom-Armasm $curText $StackSize
    [System.IO.File]::WriteAllText($masterPath, $gnu, $enc)
    Copy-Item $masterPath $startPath -Force
}

# refresh stack size inside the master + build file
if ($isGnu -or (Test-Path $masterPath)) {
    $mp = if (Test-Path $masterPath) { $masterPath } else { $startPath }
    $g = [System.IO.File]::ReadAllText($mp)
    $g2 = [regex]::Replace($g, '(\.equ\s+Stack_Size,\s*)0x[0-9A-Fa-f]+', ('${1}' + $StackSize))
    if ($g2 -ne $g) { [System.IO.File]::WriteAllText($mp, $g2, $enc); Copy-Item $mp $startPath -Force }
}

# ---------------------------------------------------------------- 2. options
$t = [System.IO.File]::ReadAllText($uvproj)
if ($t -notmatch '<uAC6>') { Write-Host '[WARN] no <uAC6> tag: this project file is very old.' -ForegroundColor Yellow }
$t = $t -replace '<uAC6>\d+</uAC6>', '<uAC6>1</uAC6>'
# keep the "ARM Compiler" dropdown consistent with reality: if it still points
# at AC5 (ARMCC), switch it to V6.22 so the GUI cannot silently flip back
if ($t -match '<pCCUsed>[^<]*ARMCC[^<]*</pCCUsed>') {
    $t = $t -replace '<pCCUsed>[^<]*</pCCUsed>', '<pCCUsed>6220000::V6.22::ARMCLANG</pCCUsed>'
}
$t = $t -replace '<ClangAsOpt>\d+</ClangAsOpt>', '<ClangAsOpt>2</ClangAsOpt>'
$t = [regex]::Replace($t, '(<Cads>[\s\S]*?<MiscControls>)[\s\S]*?(</MiscControls>)',
     '$1-Wno-unknown-warning-option$2')
$t = [regex]::Replace($t, '(<Aads>[\s\S]*?<MiscControls>)[\s\S]*?(</MiscControls>)',
     '$1-Wno-unknown-warning-option -Wno-unused-command-line-argument$2')
$t = [regex]::Replace($t, '(<LDads>[\s\S]*?<Misc>)[\s\S]*?(</Misc>)',
     '$1--diag_suppress=L6306$2')

# backup of the untouched project file (only the first time)
$pjBak = $uvproj + '.orig_backup'
if (-not (Test-Path $pjBak)) { Copy-Item $uvproj $pjBak -Force }

[System.IO.File]::WriteAllText($uvproj, $t, $enc)

# ---------------------------------------------------------------- 3. report
$ok = $true
$checks = [ordered]@{
    '<uAC6>1</uAC6>'                    = 'ARM Compiler 6 selected'
    '<ClangAsOpt>2</ClangAsOpt>'        = 'Assembler = armclang (GNU syntax)'
    '-Wno-unused-command-line-argument' = 'asm misc controls patched'
    '--diag_suppress=L6306'             = 'linker L6306 suppressed'
}
foreach ($k in $checks.Keys) { if ($t -notlike "*$k*") { $ok = $false; Write-Host ('[MISSING] ' + $checks[$k]) -ForegroundColor Red } }
if (-not (Test-Path $masterPath)) { $ok = $false; Write-Host '[MISSING] master startup *_ac6.s' -ForegroundColor Red }

if ($ok) {
    Write-Host ('[OK] compiler/assembler/startup ready. startup = ' + (Split-Path $startPath -Leaf) + ', stack = ' + $StackSize) -ForegroundColor Green
    Write-Host '[OK] Rebuild in Keil (close and reopen the project if it is open).'
} else {
    Write-Host '[WARN] self check failed - open Options for Target -> Asm and set Assembler manually.' -ForegroundColor Yellow
}